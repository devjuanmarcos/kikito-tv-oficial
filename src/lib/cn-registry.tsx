export type CnGroup = "tokens" | "inputs" | "display" | "data" | "feedback" | "layout" | "overlays" | "charts";

export interface PropDoc {
  name: string;
  type: string;
  default?: string;
  required?: boolean;
  description: string;
}

export type CnStatus = "stable" | "beta" | "dev";

/** A variant of a Super component (absorbed sub-component or prop value). */
export interface CnVariantMeta {
  /** Prop that activates this variant (e.g. "mode", "type", "variant"). */
  prop: string;
  /** Value of the prop (e.g. "multi", "number", "outline"). */
  value: string;
  /** Human label shown in the variant selector / search chip. */
  label: string;
  /** Development status; "dev" renders an "Em desenvolvimento" badge. */
  status: CnStatus;
  /** Optional note shown next to the badge. */
  note?: string;
  /** Extra search terms that resolve to this variant (e.g. legacy names). */
  aliases?: string[];
}

export interface CnComponentMeta {
  name: string;
  title: string;
  group: CnGroup;
  description: string;
  /** Relative path from project root to main component file */
  filePath?: string;
  /** npm packages required beyond react */
  dependencies?: string[];
  /** Internal path aliases required (e.g. '@/lib/utils') */
  peerDeps?: string[];
  props?: PropDoc[];
  /** TSX usage example shown in the docs */
  usage?: string;
  /** Overall maturity of the component; default "stable". */
  status?: CnStatus;
  /** Variants this Super component exposes (selector + search). */
  variants?: CnVariantMeta[];
  /** Legacy component names this Super absorbs — hidden from sidebar nav, kept in search. */
  absorbs?: string[];
  /** Extra free-form search keywords. */
  keywords?: string[];
}

/** Returns the usage example for a component (manual → map → auto-generated fallback) */
export function generateUsage(meta: CnComponentMeta, usageMap: Record<string, string> = {}): string {
  if (meta.usage) return meta.usage;
  if (usageMap[meta.name]) return usageMap[meta.name];

  const componentName = meta.title.replace(/\s+/g, "");
  const importPath = `@/components/ui/cn/${meta.name}/${componentName}`;
  return `import { ${componentName} } from "${importPath}";\n\nexport function ${componentName}Example() {\n  return (\n    <${componentName} />\n  );\n}`;
}

