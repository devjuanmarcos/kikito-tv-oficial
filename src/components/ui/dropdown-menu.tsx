// ── Helper hook: detect open state via MutationObserver ───────────────────────
function useDataStateOpen(ref: React.RefObject<HTMLDivElement | null>): boolean {
  const [isOpen, setIsOpen] = React.useState(false);

  React.useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const check = () => setIsOpen(el.dataset.state === "open");
    const observer = new MutationObserver(check);
    observer.observe(el, { attributes: true, attributeFilter: ["data-state"] });
    check();
    return () => observer.disconnect();
  }, [ref]);

  return isOpen;
}

// ── DropdownMenuSubContent ────────────────────────────────────────────────────
const DropdownMenuSubContent = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.SubContent>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.SubContent>
>(({ className, children, ...props }, ref) => {
  const contentRef = React.useRef<HTMLDivElement>(null);
  const isOpen = useDataStateOpen(contentRef);

  return (
    <DropdownMenuPrimitive.SubContent
      ref={(node) => {
        (contentRef as React.MutableRefObject<HTMLDivElement | null>).current = node;
        if (typeof ref === "function") ref(node);
        else if (ref) (ref as React.MutableRefObject<HTMLDivElement | null>).current = node;
      }}
      forceMount
      style={{ pointerEvents: isOpen ? "auto" : "none" }}
      className={cn(
        "z-50 min-w-[8rem] overflow-hidden rounded-md border border-border bg-popover p-1 text-popover-foreground shadow-lg",
        className
      )}
      {...props}
    >
      <AnimatePresence>
        {isOpen && (
          <motion.div
            initial={{ opacity: 0, scale: 0.95 }}
            animate={{ opacity: 1, scale: 1 }}
            exit={{ opacity: 0, scale: 0.95 }}
            transition={{ duration: 0.2, ease: "easeOut" }}
            className="contents"
          >
            {children}
          </motion.div>
        )}
      </AnimatePresence>
    </DropdownMenuPrimitive.SubContent>
  );
});
DropdownMenuSubContent.displayName = DropdownMenuPrimitive.SubContent.displayName;

